import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const htmlPath = path.join(root, 'app/crm-registro-cliente.html');
const html = fs.readFileSync(htmlPath, 'utf8');
const escJs = html.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
const escTs = html.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

const js =
  "(function (global) {\n" +
  "  'use strict';\n" +
  '  global.__CROZZO_CRM_REG_HTML_TEMPLATE = `' +
  escJs +
  '`;\n' +
  "})(typeof window !== 'undefined' ? window : globalThis);\n";

const ts =
  '// Auto-generated by scripts/gen-crm-registro-template.mjs — do not edit\n' +
  'export const CRM_REGISTRO_HTML_TEMPLATE = `' +
  escTs +
  '`;\n';

fs.writeFileSync(path.join(root, 'app/modules/CrozzoCrmRegistroTemplate.js'), js, 'utf8');
fs.writeFileSync(
  path.join(root, 'supabase/functions/crm-registro-cliente/template.ts'),
  ts,
  'utf8'
);
console.log('[gen-crm-registro-template] OK');
