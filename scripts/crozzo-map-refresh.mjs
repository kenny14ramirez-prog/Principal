#!/usr/bin/env node
/**
 * Regenera mapas auto-actualizables en docs/maps/ (boot, secciones PosMain, exports, índice archivos).
 * Uso: npm run map:refresh
 */
import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const mapsDir = join(root, 'docs', 'maps');
const POSMAIN = join(root, 'app', 'core', 'CrozzoPosMain.js');
const INDEX_HTML = join(root, 'app', 'index.html');

function read(rel) {
  return readFileSync(join(root, rel), 'utf8');
}

function writeMap(name, body) {
  const header =
    '<!-- AUTO-GENERATED by scripts/crozzo-map-refresh.mjs — no editar a mano -->\n\n';
  writeFileSync(join(mapsDir, name), header + body, 'utf8');
}

function gitShortHead() {
  try {
    return spawnSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: root, encoding: 'utf8' }).stdout.trim();
  } catch (_) {
    return '?';
  }
}

function semver() {
  try {
    const j = JSON.parse(read('releases/latest.json'));
    return j.semver || j.version || '?';
  } catch (_) {
    return '?';
  }
}

function parseBootOrder(html) {
  const re = /<script\s+src="([^"]+)"/g;
  const out = [];
  let m;
  while ((m = re.exec(html))) {
    if (!m[1].startsWith('http')) out.push(m[1].replace(/^\//, ''));
  }
  return out;
}

function parsePosMainSections(text) {
  const lines = text.split(/\r?\n/);
  const sections = [];
  for (let i = 0; i < lines.length - 2; i++) {
    if (/^\/\/ =+$/.test(lines[i]) && /^\/\/ =+$/.test(lines[i + 2])) {
      const title = lines[i + 1].replace(/^\/\/\s?/, '').trim();
      if (title) sections.push({ title, line: i + 1 });
    }
  }
  for (let s = 0; s < sections.length; s++) {
    sections[s].end =
      s + 1 < sections.length ? sections[s + 1].line - 1 : lines.length;
  }
  return sections;
}

function parseWindowExports(text) {
  const lines = text.split(/\r?\n/);
  const out = [];
  const re = /^window\.(crozzo[A-Za-z0-9_]+|applyPosRuntimeSnapshot|navigateTo|initPOS)\s*=/;
  for (let i = 0; i < lines.length; i++) {
    const m = lines[i].match(re);
    if (m) out.push({ name: m[1], line: i + 1 });
  }
  return out;
}

function parseSyncSymbols(text) {
  const lines = text.split(/\r?\n/);
  const keys =
    /Sync|Runtime|Cart|Comanda|Presence|Slot|Mesa|cloud|Lan|merge|Remote|applyPos/i;
  const out = [];
  const reFn = /^function (crozzo[A-Za-z0-9_]+)/;
  for (let i = 0; i < lines.length; i++) {
    const m = lines[i].match(reFn);
    if (m && keys.test(m[1])) out.push({ name: m[1], line: i + 1 });
  }
  return out;
}

function listJsFiles(dir, base) {
  const out = [];
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory()) out.push(...listJsFiles(p, base));
    else if (name.endsWith('.js')) {
      const rel = relative(root, p).replace(/\\/g, '/');
      const lines = readFileSync(p, 'utf8').split(/\r?\n/).length;
      out.push({ rel, lines });
    }
  }
  return out.sort((a, b) => a.rel.localeCompare(b.rel));
}

mkdirSync(mapsDir, { recursive: true });

const now = new Date().toISOString();
const meta = {
  generatedAt: now,
  semver: semver(),
  gitHead: gitShortHead(),
  posMainLines: existsSync(POSMAIN) ? readFileSync(POSMAIN, 'utf8').split(/\r?\n/).length : 0,
};
writeFileSync(join(mapsDir, 'META.json'), JSON.stringify(meta, null, 2), 'utf8');

// BOOT-ORDER
const scripts = parseBootOrder(readFileSync(INDEX_HTML, 'utf8'));
let bootMd = '# Orden de arranque (scripts)\n\n';
bootMd += `Generado: ${now} · v${meta.semver}\n\n`;
bootMd += '| # | Script |\n|---|--------|\n';
scripts.forEach((s, i) => {
  bootMd += `| ${i + 1} | \`${s}\` |\n`;
});
bootMd += '\n## Tramo crítico sync (no reordenar)\n\n';
bootMd += '```\nOpAckRegistry → LanActionDedup → OpFanout → LanSyncBridge → LanOpsSync\n';
bootMd += '→ PosMain → PosRuntimeCloud → … → StartupReady → PosBoot\n```\n';
writeMap('BOOT-ORDER.md', bootMd);

// POSMAIN sections
const posText = readFileSync(POSMAIN, 'utf8');
const sections = parsePosMainSections(posText);
let secMd = '# PosMain — secciones por línea\n\n';
secMd += `Archivo: \`app/core/CrozzoPosMain.js\` · ${meta.posMainLines} líneas\n\n`;
secMd += '| Líneas | Sección |\n|--------|--------|\n';
sections.forEach((s) => {
  secMd += `| ${s.line}–${s.end} | ${s.title} |\n`;
});
secMd += '\n## Zona sync operativo (buscar aquí primero)\n\n';
secMd += '| Líneas | Tema |\n|--------|------|\n';
sections
  .filter((s) => /cart|runtime|sync|mesa|cajero|tablet|comanda|presence|slot/i.test(s.title))
  .forEach((s) => {
    secMd += `| ${s.line}–${s.end} | ${s.title} |\n`;
  });
writeMap('POSMAIN-SECTIONS.md', secMd);

// Exports + sync symbols
const exports = parseWindowExports(posText);
let expMd = '# PosMain — exports globales (window.*)\n\n';
expMd += 'API pública usada por otros módulos. Buscar por nombre antes de renombrar.\n\n';
expMd += '| Línea | Símbolo |\n|-------|--------|\n';
exports.forEach((e) => {
  expMd += `| ${e.line} | \`${e.name}\` |\n`;
});
writeMap('POSMAIN-EXPORTS.md', expMd);

const syncSyms = parseSyncSymbols(posText);
let symMd = '# PosMain — símbolos sync/mesa/carrito\n\n';
symMd += 'Subset filtrado (nombre contiene Sync|Runtime|Cart|Comanda|Presence|Slot|Mesa|Remote|merge|cloud|Lan).\n\n';
symMd += '| Línea | Función |\n|-------|--------|\n';
syncSyms.forEach((s) => {
  symMd += `| ${s.line} | \`${s.name}\` |\n`;
});
writeMap('POSMAIN-SYNC-SYMBOLS.md', symMd);

// FILES index
const dirs = ['app/core', 'app/infra', 'app/modules', 'app/ui'];
let filesMd = '# Índice de archivos JS (líneas)\n\n';
dirs.forEach((d) => {
  filesMd += `\n## ${d}/\n\n`;
  filesMd += '| Líneas | Archivo |\n|--------|--------|\n';
  listJsFiles(join(root, d), d).forEach((f) => {
    filesMd += `| ${f.lines} | \`${f.rel}\` |\n`;
  });
});
writeMap('FILES-INDEX.md', filesMd);

// Update INDEX snippet timestamp
const indexPath = join(mapsDir, 'INDEX.md');
if (existsSync(indexPath)) {
  let idx = readFileSync(indexPath, 'utf8');
  idx = idx.replace(
    /\*\*Última regeneración:\*\*[^\n]*/,
    `**Última regeneración:** ${now} · v${meta.semver} · \`${meta.gitHead}\``
  );
  writeFileSync(indexPath, idx, 'utf8');
}

// Known issues MD desde JSON
const issuesRun = spawnSync(process.execPath, [join(root, 'scripts', 'crozzo-known-issues.mjs'), 'refresh'], {
  cwd: root,
  encoding: 'utf8',
  stdio: 'pipe',
});
if (issuesRun.status !== 0) {
  console.warn('[map:refresh] issues:refresh falló:', (issuesRun.stderr || '').slice(0, 200));
}

console.log('[map:refresh] OK → docs/maps/');
console.log('  META.json, BOOT-ORDER.md, POSMAIN-SECTIONS.md, POSMAIN-EXPORTS.md');
console.log('  POSMAIN-SYNC-SYMBOLS.md, FILES-INDEX.md, KNOWN-ISSUES.md');
